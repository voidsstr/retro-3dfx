int init_conform(conform_state *state, int local_argc, char **local_argv)
{
  test_data *local_ptr;
  int num_tmu;

  state->test_name = test_name;
  state->test_description = test_description;

  if((state->local_data = malloc(sizeof(test_data))) == NULL) {
    // Could not allocate data for local memory
    log_perror(state,"Could not allocate memory for local data");
    return(0);
  } 

  local_ptr = (test_data *)state->local_data;
  local_ptr->debug = 0;

  // pick a random TMU
  num_tmu = nrand((int)(state->num_tmu));

  // print out test dependent args
  ++local_argv; // skip argv[0] (the test name)
  while(--local_argc) {
    if(!_stricmp(*local_argv,"-tmu") || // TMU to use
       !_stricmp(*local_argv,"/tmu")) {
      ++local_argv;
      if(!sscanf(*local_argv,"%d",&num_tmu)) {
        // bad argument
      } 
      --local_argc;
    } else if(!_stricmp(*local_argv,"-debug") || // enable debug output
              !_stricmp(*local_argv,"/debug")) {
      local_ptr->debug = 1;
    } else {
      fprintf(stderr, "Invalid argument '%s' - ignored.\n", *local_argv);
    }
    ++local_argv;
  }

  // Convert numeric TMU to argument for glide
  if(num_tmu >= state->num_tmu) {
    num_tmu = 0;
  }
  switch(num_tmu) {
  case 1:
    local_ptr->curtmu = GR_TMU1;
    break;
  case 2:
    local_ptr->curtmu = GR_TMU2;
    break;
  default:
    local_ptr->curtmu = GR_TMU0;
    break;
  }

  // don't use any visuals with aux buffers
  state->num_aux_bufs = 0;

  // use 100x100 image area
  state->conform_width = 100;
  state->conform_height = 100;

  // xycheck/xylimit not supported.
  state->xycheck = 0;
  state->xylimit = 0;

  // tiling not supported
  state->tile = 0;

  // setup image file names
  // this is manditory
  frame_name("color-combine",state);
  img_file_type(IMG_P6,state);

  // Initialization complete
  return(-1);
}

void close_conform(conform_state *state)
{
  // Free up local data
  free(state->local_data);
}

int do_conform(conform_state *state)
{
  test_data *local_ptr;
  GrColor_t clearcolor;
  int num_tmu;
  int comb;
  FxU32 *screen;
  char outstr[128];
  
  local_ptr = (test_data *)state->local_data;
  
  // if multiple reps - randomize
  if(state->num_reps != 1) {
    // randomize TMU
    num_tmu = nrand(state->num_tmu);
    switch(num_tmu) {
    case 1:
      local_ptr->curtmu = GR_TMU1;
      break;
    case 2:
      local_ptr->curtmu = GR_TMU2;
      break;
    default:
      local_ptr->curtmu = GR_TMU0;
      break;
    }
  }
  
  // write record of TMU to loog file
  switch(local_ptr->curtmu) {
  case 1:
    log_message(state,"Using TMU 1");
    break;
  case 2:
    log_message(state,"Using TMU 2");
    break;
  default:
    log_message(state,"Using TMU 0");
    break;
  }
  
  // allocate screen for automated compare
  if((screen = 
      (FxU32 *)malloc(state->conform_width*state->conform_height*sizeof(FxU32))) == NULL) {
    // fail
    log_message(state,"Could not allocate memory buffer for screen image");
  }

  for(comb = 0; comb < NUM_COMBINE; comb++) {
    // clear front buffer to lightgrey
    clearcolor = rgbacolor(state, 0x2f2f2fff);
    grRenderBuffer(GR_BUFFER_FRONTBUFFER);
    grColorMask(FXTRUE,FXFALSE);
    grDepthMask(FXFALSE);
    grCoordinateSpace(GR_WINDOW_COORDS);
    vmgrClipWindow(state,
                   state->conform_x,
                   state->conform_y,
                   state->conform_x+state->conform_width,
                   state->conform_y+state->conform_height);
    
    grViewport(state->conform_x, state->conform_y, 
               state->conform_width, state->conform_height);
    
    setup_prim(state);
    
    grBufferClear(clearcolor,0x0000,0x00000000);
    
    // Init vertex data
    local_ptr->verts[0].x = 18.0f;
    local_ptr->verts[0].y = 18.0f;
    local_ptr->verts[1].x = 18.0f + 64.0f;
    local_ptr->verts[1].y = 18.0f;
    local_ptr->verts[2].x = 18.0f + 64.0f;
    local_ptr->verts[2].y = 18.0f + 64.0f;
    local_ptr->verts[3].x = 18.0f;
    local_ptr->verts[3].y = 18.0f + 64.0f;
    
    // Init constant color to yellow & 1/2 alpha
    grConstantColorValue(rgbacolor(state,0xffff007f));
    
    // Init Interpolated colors
    local_ptr->verts[0].a = 255.0f;
    local_ptr->verts[0].r = 0.0f;
    local_ptr->verts[0].g = 0.0f;
    local_ptr->verts[0].b = 0.0f;
    local_ptr->verts[1].a = 0.0f;
    local_ptr->verts[1].r = 0.0f;
    local_ptr->verts[1].g = 0.0f;
    local_ptr->verts[1].b = 0.0f;
    local_ptr->verts[2].a = 0.0f;
    local_ptr->verts[2].r = 255.0f;
    local_ptr->verts[2].g = 255.0f;
    local_ptr->verts[2].b = 255.0f;
    local_ptr->verts[3].a = 255.0f;
    local_ptr->verts[3].r = 255.0f;
    local_ptr->verts[3].g = 255.0f;
    local_ptr->verts[3].b = 255.0f;
    
    // Choose colorcombine
    grColorCombine(combine[comb].function,
                   combine[comb].factor,
                   combine[comb].local,
                   combine[comb].other,
                   combine[comb].invert);

    // Choose matching alphacombine
    grAlphaCombine(GR_COMBINE_FUNCTION_LOCAL_ALPHA,
                   GR_COMBINE_FACTOR_ONE,
                   combine[comb].alpha,
                   GR_COMBINE_LOCAL_NONE,
                   FXFALSE);        
    
    // Draw square
    grDrawTriangle(&(local_ptr->verts[0]), 
                   &(local_ptr->verts[1]), 
                   &(local_ptr->verts[2]));
    
    grDrawTriangle(&(local_ptr->verts[0]), 
                   &(local_ptr->verts[2]), 
                   &(local_ptr->verts[3]));
    
    end_frame(END_OP_SAVE_TO_MEM, 
              state, 
              (void **)&screen, 
              END_BUFFER_FRONTBUFFER);

    sprintf(outstr,"frame = %d",comb);
    log_message(state,outstr);

    if (!log_status(state, 
                    check_frame(state, screen,
                                combine[comb].function,
                                combine[comb].factor,
                                combine[comb].local,
                                combine[comb].other,
                                combine[comb].alpha,
                                combine[comb].invert),
                    "screen vs. emulated")) {
      free(screen);
      return(TEST_FAIL);
    }
  }

  free(screen);
  
  return(TEST_PASS); 
}

