void setup_prim(conform_state *state)
{
  test_data *local_ptr;
  GrChipID_t passtmu;
  FxU32 baseaddr;
  FxU16 *buffer;
  int i;

  local_ptr = (test_data *)state->local_data;

  grVertexLayout(GR_PARAM_XY,  GR_VERTEX_X_OFFSET << 2, GR_PARAM_ENABLE);  
  grVertexLayout(GR_PARAM_Q , GR_VERTEX_OOW_OFFSET << 2, GR_PARAM_ENABLE);
  grVertexLayout(GR_PARAM_A,  GR_VERTEX_A_OFFSET << 2, GR_PARAM_ENABLE);  
  grVertexLayout(GR_PARAM_RGB,  GR_VERTEX_R_OFFSET << 2, GR_PARAM_ENABLE);  
  // set for max 3 TMUs for now
  grVertexLayout(GR_PARAM_ST0, GR_VERTEX_SOW_TMU0_OFFSET << 2,
                 GR_PARAM_ENABLE);
  grVertexLayout(GR_PARAM_Q0, GR_VERTEX_OOW_TMU0_OFFSET << 2,
                 GR_PARAM_ENABLE);
  grVertexLayout(GR_PARAM_ST1, GR_VERTEX_SOW_TMU1_OFFSET << 2,
                 GR_PARAM_ENABLE);
  grVertexLayout(GR_PARAM_Q1, GR_VERTEX_OOW_TMU1_OFFSET << 2,
                 GR_PARAM_ENABLE);
  grVertexLayout(GR_PARAM_ST2, GR_VERTEX_SOW_TMU2_OFFSET << 2,
                 GR_PARAM_ENABLE);
  grVertexLayout(GR_PARAM_Q2, GR_VERTEX_OOW_TMU2_OFFSET << 2,
                 GR_PARAM_ENABLE);

  grAlphaBlendFunction(GR_BLEND_ONE,
                       GR_BLEND_ZERO,
                       GR_BLEND_ONE,
                       GR_BLEND_ZERO);

  grAlphaTestReferenceValue(0x00);
  grAlphaTestFunction(GR_CMP_NOTEQUAL);

  // Setup other TMUs to pass thru
  for(i = 0; i< local_ptr->curtmu; i++) {
    switch(i) {
    case 1:
      passtmu = GR_TMU1;
      break;
    case 2:
      passtmu = GR_TMU2;
      break;
    default:
      passtmu = GR_TMU0;
      break;
    }
    grTexCombine(passtmu,
                 GR_COMBINE_FUNCTION_SCALE_OTHER,
                 GR_COMBINE_FACTOR_ONE,
                 GR_COMBINE_FUNCTION_SCALE_OTHER,
                 GR_COMBINE_FACTOR_ONE,
                 FXFALSE, FXFALSE );
  }

  grTexCombine(local_ptr->curtmu,
               GR_COMBINE_FUNCTION_LOCAL,
               GR_COMBINE_FACTOR_NONE,
               GR_COMBINE_FUNCTION_LOCAL,
               GR_COMBINE_FACTOR_ONE,
               FXFALSE, FXFALSE );
  
  grTexClampMode(local_ptr->curtmu, 
                 GR_TEXTURECLAMP_WRAP, GR_TEXTURECLAMP_WRAP);

  grTexFilterMode(local_ptr->curtmu,
                  GR_TEXTUREFILTER_POINT_SAMPLED,
                  GR_TEXTUREFILTER_POINT_SAMPLED );

  grTexMipMapMode(local_ptr->curtmu,
                  GR_MIPMAP_NEAREST,
                  FXFALSE );

  grTexLodBiasValue(local_ptr->curtmu, 0.0f);

  // Init texture
  if((buffer = (FxU16 *)malloc(64*64*2)) == NULL) {
    // fail
    log_message(state,"Could not allocate memory buffer for texture map");
  }
  
  local_ptr->info.data = buffer;
  texture_gen(local_ptr);
  
  // get random texture address
  baseaddr = texture_base(state, local_ptr->curtmu, GR_MIPMAPLEVELMASK_BOTH, &(local_ptr->info));
  
  // download texture
  grTexDownloadMipMap(local_ptr->curtmu,
                      baseaddr,
                      GR_MIPMAPLEVELMASK_BOTH,
                      &(local_ptr->info));
  
  grTexSource(local_ptr->curtmu,
              baseaddr,
              GR_MIPMAPLEVELMASK_BOTH,
              &(local_ptr->info));

  free(buffer);
}

void texture_gen(test_data *local_ptr)
{
  int width;
  int height;
  int i;

  height = 64;
  width = 64;
  local_ptr->info.aspectRatioLog2 = GR_ASPECT_LOG2_1x1;
  
  local_ptr->info.format = GR_TEXFMT_ARGB_4444;
  word_texture((FxU16 *)local_ptr->info.data,
               height, width,
               0xff00, 0xf0f0, 0xf00f, 0x000f);
  
  local_ptr->info.smallLodLog2 = GR_LOD_LOG2_64;
  local_ptr->info.largeLodLog2 = GR_LOD_LOG2_64;

  // setup vertex data for all TMUs
  for(i = 0; i < GRVERTEX_NUM_TMU; i++) {
    local_ptr->verts[0].tmuvtx[i].sow = 0.0f;
    local_ptr->verts[0].tmuvtx[i].tow =0.0f;
    local_ptr->verts[0].oow = 1.0f;  
    local_ptr->verts[0].tmuvtx[i].oow = 1.0f;
    
    local_ptr->verts[1].tmuvtx[i].sow = 256.0f;
    local_ptr->verts[1].tmuvtx[i].tow = 0.0f;
    local_ptr->verts[1].oow = 1.0f;  
    local_ptr->verts[1].tmuvtx[i].oow = 1.0f;
    
    local_ptr->verts[2].tmuvtx[i].sow = 256.0f;
    local_ptr->verts[2].tmuvtx[i].tow = 256.0f;
    local_ptr->verts[2].oow = 1.0f;  
    local_ptr->verts[2].tmuvtx[i].oow = 1.0f;
    
    local_ptr->verts[3].tmuvtx[i].sow = 0.0f;
    local_ptr->verts[3].tmuvtx[i].tow = 256.0f;
    local_ptr->verts[3].oow = 1.0f;  
    local_ptr->verts[3].tmuvtx[i].oow = 1.0f;
  }
}

void word_texture(FxU16 *tmp, int height, int width, 
                  FxU16 red, FxU16 grn, FxU16 blu_a, FxU16 blu)
{
  int i,j;

  for(i=0; i<height; i++) {
    for(j=0; j<width ; j++) {
      if((i==0) || (i==(height-2)) ||
         (j==0) || (j==(width-2))) {
        // red border
        *tmp++ = red;
      } else if ((i==1) || (i==(height-1)) ||
                 (j==1) || (j==(width-1))) {
        // green interior border
        *tmp++ = grn;
      } else {
        // blue center
        if((i%3)&&(j%3)) {
          // alpha != 0
          *tmp++ = blu_a;
        } else {
          // alpha == 0
          *tmp++ = blu;
        }
      }
    }
  }
}

TestResult check_frame(conform_state *state,
                       FxU32 *screen,
                       GrCombineFunction_t function,
                       GrCombineFactor_t factor,
                       GrCombineLocal_t local,
                       GrCombineOther_t other,
                       GrCombineLocal_t alpha,
                       FxBool invert)
{
  FxU32 *tmp, *screen_top;
  TestResult status = TEST_PASS;
  int x, y;
  char outstr[128];
  float expected_r;
  float expected_g;
  float expected_b;
  float alphaval;
  float texturer;
  float textureg;
  float textureb;
  float texturea;
  Color4D expected_color;

  test_data *local_ptr = (test_data *)state->local_data;

  screen_top = tmp = screen;
  tmp += 18 +(18 * state->conform_width);
  // go to first active pixel
  for(y = 0; y < 64; y++) {
    for(x = 0; x < 64; x++) {
      // setup alpha
      if(alpha == GR_COMBINE_LOCAL_CONSTANT) {
        // use constant alpha
        alphaval = 0.5f;
      } else {
        // use iterated alpha
        alphaval = ((float)(63-x))/63.0f; // inverse x
      }

      // setup texture color
      if((x==0) || (x==62) ||
         ((y)==0) || ((y)==62)) {
        // red border
        texturer = 1.0f;
        textureg = 0.0f;
        textureb = 0.0f;
        texturea = 1.0f;
      } else if ((x==1) || (x==63) ||
                 ((y)==1) || ((y)==63)) {
        // green interior border
        texturer = 0.0f;
        textureg = 1.0f;
        textureb = 0.0f;
        texturea = 1.0f;
      } else {
        // blue center
        if((x%3)&&((y)%3)) {
          // alpha != 0
          texturer = 0.0f;
          textureg = 0.0f;
          textureb = 1.0f;
          texturea = 1.0f;
        } else {
          // alpha == 0
          texturer = 0.0f;
          textureg = 0.0f;
          textureb = 1.0f;
          texturea = 0.0f;
        }
      }

      vmgrColorCombine(function,
                       factor,
                       local,
                       other,
                       invert,
                       &expected_r,
                       &expected_g,
                       &expected_b,
                       ((float)(y))/63.0f, // iterated (inverse y)
                       ((float)(y))/63.0f, // iterated (inverse y)
                       ((float)(y))/63.0f, // iterated (inverse y)
                       alphaval, // iterated alpha
                       1.0f, // yellow
                       1.0f, // 
                       0.0f, // 
                       alphaval, // contant alpha
                       texturer,
                       textureg,
                       textureb,
                       texturea);


      expected_color.red = expected_r;
      expected_color.green = expected_g;
      expected_color.blue = expected_b;

      if (!compare_color(state, *tmp, &expected_color)) {
        sprintf(outstr, "@(%d %d), actual(0x%x) != expected(0x%x 0x%x 0x%x)", x, y,
                *tmp,
                (int)(expected_color.red * 255.5f),
                (int)(expected_color.green * 255.5f),
                (int)(expected_color.blue * 255.5f));
        log_message(state,outstr);
        status = TEST_FAIL;
        if (local_ptr->debug) {
          *tmp = 0x00000FFF; // debug, mark mismatched pixels
        }
      }
      ++tmp;
    }
    // skip border
    tmp += state->conform_width-64;
  }

  if (local_ptr->debug) {
    char filename[128];
    sprintf(filename, "%s/emu-%s-%02d", 
            state->output_dir, test_name, state->framecnt-1);
    save_image_to_file(state, filename, screen_top,    
                       state->conform_width, state->conform_height,
                       FXTRUE);
  }

  return(status);
}
