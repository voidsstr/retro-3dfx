/*----------------------------------------------------------------------
Function name:  FindMode

Description:    -

Return:         -
----------------------------------------------------------------------*/
int FindMode(TIMING_PARAMS * ioTimingRequest)
{
#define FN_NAME "FindMode"
#define FN_LEVEL 0
  TIMING_PARAMS *found;
  short i;
  short refresh = 0;
  int ret = -1;
  
  LOG_ENTRY(FN_LEVEL);
  LOG_PRINTF(FN_LEVEL, "recalculate crtc values...\n" );

  for (i=0; baseline_timings[i].width!=0; i++)
  {
    if (baseline_timings[i].width == ioTimingRequest->width &&
        baseline_timings[i].height == ioTimingRequest->height )
    {
      if ( baseline_timings[i].refresh > refresh && baseline_timings[i].refresh <= ioTimingRequest->refresh  )
      {
        found = &baseline_timings[i];
        refresh = baseline_timings[i].refresh;
      }
      ret = 0;
    }
  }

  if ( !ret )
    *ioTimingRequest = *found;
  else
    LOG_PRINTF(FN_LEVEL, "### error, the requested timings were not found!!!\n" );
    
  LOG_EXIT(FN_LEVEL,ret);
  return (ret);

#undef FN_NAME  
#undef FN_LEVEL
}


