# return pointer to SST at specified WRAP, CHIP, or TREX
sub SST_WRAP	{ my($sst,$n) = @_; return (($n)*0x4000+($sst)); }
sub SST_CHIP	{ my($sst,$n) = @_; return (($n)*0x400+($sst)); }
sub SST_TMU	{ my($sst,$n) = @_; return ((0x800<<($n))+($sst)); }
sub SST_TREX	{ my($sst,$n) = @_; return SST_TMU($sst,$n); }

