# this crazy macro fixes the binary point within a floating point
# number so that it has 'fracbits' to the right of the binary point
# it also adds a '1' bit to the MSB so that slightly negative numbers
# end up looking like twos complement numbers (they carry out from the '1')
sub FLOAT_FIX	{ my($f,$fracbits) = @_; return (($f)+(3<<(22-($fracbits)))); }
sub SST_FLOAT	{ my($f,$scale,$shift) = @_; return (($f)*(($scale)*(1<<$shift))); }
sub SST_TLOD_MINMAX { my($lodmin,$lodmax) = @_; 
                      my $t = ((($lodmin) << ($h3def{SST_LODMIN_SHIFT})) |
			       (($lodmax) << ($h3def{SST_LODMAX_SHIFT})));
                      return $t;
		}
sub SST_TLOD_MINMAX_INT { my($lodmin,$lodmax) = @_; 
                      my $t = ((($lodmin) << ($h3def{SST_LOD_FRACBITS}+$h3def{SST_LODMIN_SHIFT})) |
			       (($lodmax) << ($h3def{SST_LOD_FRACBITS}+$h3def{SST_LODMAX_SHIFT})));
                      return $t;
		}

# this crazy macro tests the sign bit of a float by loading it into
# an integer register and then testing the sign bit of the integer
sub FLOAT_ISNEG	{ my($f) = @_; return (int($f) < 0); }

# these crazy macros returns the sign of a number (1 if >= 0; -1 if < 0)
sub ISIGN	{ my($x) = @_; return ((($x) | 0x40000000) >> 30); }
sub FSIGN	{ my($f) = @_; return ISIGN($f); }

sub BIT 	{ my($n) = @_; return 1 << @_[0]; }
sub SST_MASK 	{ my($n) = @_; my($s)=0;
		  $s = $s + BIT($n) while ( $n-- > 0 );
		  return $s; }

