#
# addToDefs(\%href)
#
# load a hash table's entries into %h3def
#
sub addToDefs {
    my($href) = @_;
    foreach $key ( keys %$href ) {
	$h3def{$key} = $href->{$key};
#	printf "adding %s => 0x%x\n",$key,$h3def{$key};
    }
}

#
# PARSE($regname,$data)
#
# parse $data into the fields defined for $regname and display the results
#
sub PARSE {
    my($regname,$data) = @_;
    my($name, $val, $mask, $shift, $found, $maskall);
    my(%lines, $aline, $k);
    my(%h);
    
    %h = %{$h3field{$regname}};
    printf "%s = 0x%x\n",$regname,$data;

    if ( exists $h3field{$regname} ) {
	$maskall = 0;

	# Loop thru fields, sorted from lsb's to msb's. This sort sub is
	# numerically sorting the keys based on their values (which are bit masks).
	foreach $name ( sort {$h3field{$regname}{$a} <=> $h3field{$regname}{$b} } keys %{$h3field{$regname}}  ) {

	    # mask off field
	    $mask = $h3field{$regname}{$name};
	    $maskall |= $mask;
	    $val = $data & $mask;

	    # shift field into least significant bits
	    for ( $shift=0; $shift<32; $shift++ ) {
		last if ( ($mask>>$shift) & 0x1 );
	    }
	    $val >>= $shift;
	    $mask >>= $shift;

	    # display all multibit fields and nonzero single-bit fields
	    if ( ($val || $mask>1) && $name !~ /SHIFT/ ) {
		printf "\t%-30s\t0x%x",$name,$val;
		if ( exists $h3fieldv{$name} ) {
		    $found = 0;
		    # loop thru names for field values
		    while ( ($token,$tval) = each %{$h3fieldv{$name}} ) {
			( $found = 1, print " ($token)" ) if ( ($tval>>$shift) == $val );
		    }
		    print " (undefined)" if (!$found);
		}
		print "\n";
	    }
	}
	printf "\t*** invalid bits = 0x%x ***\n",$data&(~$maskall) if ($data&(~$maskall));
    }
}


